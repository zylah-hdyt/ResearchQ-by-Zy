"""Corrected word timings + subtitle phrases for the Mental VO -> src/v10-mental/words.ts"""
import json, sys
W = json.load(open(sys.argv[1]))
FIX = {'mentalu': 'mental lu', 'keterlitian,': 'ketelitian,', 'menjipulkan': 'menyimpulkan'}
words = []
for x in W:
    t = x['w']
    if t.startswith('-') and words:          # "benar -benar" -> "benar-benar"
        words[-1]['w'] += t; words[-1]['e'] = x['e']; continue
    words.append({'w': FIX.get(t, t), 's': x['s'], 'e': x['e']})
phr, cur = [], []
for i, x in enumerate(words):
    cur.append(x)
    end = x['w'][-1] in ',.?' or len(cur) >= 4
    gap = words[i + 1]['s'] - x['e'] if i + 1 < len(words) else 1
    if end or gap > 0.35:
        phr.append({'t': ' '.join(c['w'] for c in cur), 'a': cur[0]['s'], 'b': (words[i + 1]['s'] if i + 1 < len(words) else x['e'] + 0.6)})
        cur = []
merged = []
for p in phr:
    if merged and len(p['t'].split()) == 1 and merged[-1]['t'][-1] not in ',.?':
        merged[-1]['t'] += ' ' + p['t']; merged[-1]['b'] = p['b']
    else:
        merged.append(p)
phr = merged
with open(sys.argv[2], 'w') as f:
    f.write('// Generated by scripts/mental/words.py (whisper timings, spelling corrected)\n')
    f.write('export const MW: {w: string; s: number; e: number}[] = ' + json.dumps(words, ensure_ascii=False) + ';\n')
    f.write('export const PHRASES: {t: string; a: number; b: number}[] = ' + json.dumps(phr, ensure_ascii=False) + ';\n')
for p in phr: print(f"{p['a']:6.2f}-{p['b']:6.2f} {p['t']}")
