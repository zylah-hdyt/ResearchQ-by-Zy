"""Per-frame (30 fps) mouth openness + width from the VO.
Port of the Studio Pack's code/engine/lipdata.py (same model), with ffmpeg doing the band filters."""
import json, subprocess, sys, wave
import numpy as np

src, out = sys.argv[1], sys.argv[2]
FPS = 30

def band(af):
    raw = subprocess.run(['ffmpeg', '-v', 'error', '-i', src, '-af', af, '-ac', '1', '-ar', '16000', '-f', 's16le', '-'], capture_output=True, check=True).stdout
    return np.frombuffer(raw, dtype=np.int16).astype(np.float64) / 32768

sr = 16000
v = band('highpass=f=200,highpass=f=200,lowpass=f=3500,lowpass=f=3500')  # voice band
hi = band('highpass=f=2500,highpass=f=2500')                             # 'i/e/s' brightness
NF = int(len(v) / sr * FPS) + FPS
win = int(.035 * sr)
op = np.full(NF, -100.0); wd = np.zeros(NF)
for n in range(NF):
    c = int((n / FPS + .02) * sr)          # mouth leads sound by 20 ms
    a, b = max(0, c - win // 2), min(len(v), c + win // 2)
    if b <= a: continue
    r = np.sqrt((v[a:b] ** 2).mean() + 1e-12)
    op[n] = 20 * np.log10(r)
    wd[n] = np.clip(np.sqrt((hi[a:b] ** 2).mean()) / (r + 1e-9) * 2.2, 0, 1)
db = op.copy(); sp = db > -45
lo, top = np.percentile(db[sp], 10), np.percentile(db[sp], 97)
k = 8; loc = np.convolve(db, np.ones(k) / k, 'same')           # ~250 ms local mean at 30 fps
rel = np.clip((db - loc + 5) / 9, 0, 1)
lev = np.clip((db - lo) / (top - lo), 0, 1)
op = np.where(sp, .25 * lev + .75 * rel * lev ** .5, 0)
sm = np.zeros(NF); s = 0
for n in range(NF):
    s = op[n] if op[n] > s else s + (op[n] - s) * .6       # fast attack, quick release
    sm[n] = s
sm = np.clip(sm, 0, 1); wd = np.convolve(wd, np.ones(3) / 3, 'same')
with open(out, 'w') as fh:
    fh.write('// Generated by scripts/mental/lipdata.py from public/vo_mental.wav\n')
    fh.write('export const LIP_O: number[] = ' + json.dumps([round(float(a), 2) for a in sm]) + ';\n')
    fh.write('export const LIP_W: number[] = ' + json.dumps([round(float(a), 2) for a in wd]) + ';\n')
print('frames', NF, 'mean open %.2f' % sm.mean(), 'p10 %.1f p97 %.1f' % (lo, top))
